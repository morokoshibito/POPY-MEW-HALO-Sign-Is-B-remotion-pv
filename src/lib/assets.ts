const derived = new Map<string, HTMLCanvasElement>();

const sizeOf = (s: Src) => ({w: s instanceof HTMLImageElement ? s.naturalWidth : s.width, h: s instanceof HTMLImageElement ? s.naturalHeight : s.height});

/** Flat fill of the figure's shape (silhouette) in one colour. */
export const silhouette = (m: Member, k: Kind, color: string): HTMLCanvasElement => {
  const key = `sil_${m}_${k}_${color}`;
  const hit = derived.get(key);
  if (hit) return hit;
  const s = img(m, k);
  const {w, h} = sizeOf(s);
  const c = document.createElement('canvas');
  c.width = w;
  c.height = h;
  const g = c.getContext('2d')!;
  g.drawImage(s, 0, 0);
  g.globalCompositeOperation = 'source-in';
  g.fillStyle = color;
  g.fillRect(0, 0, w, h);
  derived.set(key, c);
  return c;
};

/** Two-tone version: shadows -> dark, mid -> member colour, highlights -> white. */
export const duotone = (m: Member, k: Kind, dark: string, mid: string): HTMLCanvasElement => {
  const key = `duo_${m}_${k}_${dark}_${mid}`;
  const hit = derived.get(key);
  if (hit) return hit;
  const s = img(m, k);
  const {w, h} = sizeOf(s);
  const c = document.createElement('canvas');
  c.width = w;
  c.height = h;
  const g = c.getContext('2d')!;
  g.drawImage(s, 0, 0);
  const d = g.getImageData(0, 0, w, h);
  const hex = (x: string) => [parseInt(x.slice(1, 3), 16), parseInt(x.slice(3, 5), 16), parseInt(x.slice(5, 7), 16)];
  const A = hex(dark);
  const B = hex(mid);
  const px = d.data;
  for (let i = 0; i < px.length; i += 4) {
    const l = (0.299 * px[i] + 0.587 * px[i + 1] + 0.114 * px[i + 2]) / 255;
    let r: number, gg: number, b: number;
    if (l < 0.55) {
      const k2 = l / 0.55;
      r = A[0] + (B[0] - A[0]) * k2;
      gg = A[1] + (B[1] - A[1]) * k2;
      b = A[2] + (B[2] - A[2]) * k2;
    } else {
      const k2 = (l - 0.55) / 0.45;
      r = B[0] + (255 - B[0]) * k2;
      gg = B[1] + (255 - B[1]) * k2;
      b = B[2] + (255 - B[2]) * k2;
    }
    px[i] = r;
    px[i + 1] = gg;
    px[i + 2] = b;
  }
  g.putImageData(d, 0, 0);
  derived.set(key, c);
  return c;
};

/** Line-art look: edges of the image in one colour (Sobel on luminance + alpha). */
export const lineart = (m: Member, k: Kind, color: string): HTMLCanvasElement => {
  const key = `line_${m}_${k}_${color}`;
  const hit = derived.get(key);
  if (hit) return hit;
  const s = img(m, k);
  const {w: W0, h: H0} = sizeOf(s);
  const sc = Math.min(1, 1600 / H0);
  const w = Math.round(W0 * sc);
  const h = Math.round(H0 * sc);
  const c = document.createElement('canvas');
  c.width = w;
  c.height = h;
  const g = c.getContext('2d')!;
  g.drawImage(s, 0, 0, w, h);
  const src = g.getImageData(0, 0, w, h).data;
  const lum = new Float32Array(w * h);
  for (let i = 0; i < w * h; i++) {
    const a = src[i * 4 + 3] / 255;
    lum[i] = ((0.299 * src[i * 4] + 0.587 * src[i * 4 + 1] + 0.114 * src[i * 4 + 2]) / 255) * a + (1 - a);
  }
  const out = g.createImageData(w, h);
  const hex = (x: string) => [parseInt(x.slice(1, 3), 16), parseInt(x.slice(3, 5), 16), parseInt(x.slice(5, 7), 16)];
  const [cr, cg, cb] = hex(color);
  for (let y = 1; y < h - 1; y++) {
    for (let x = 1; x < w - 1; x++) {
      const i = y * w + x;
      const gx = lum[i - w + 1] + 2 * lum[i + 1] + lum[i + w + 1] - lum[i - w - 1] - 2 * lum[i - 1] - lum[i + w - 1];
      const gy = lum[i + w - 1] + 2 * lum[i + w] + lum[i + w + 1] - lum[i - w - 1] - 2 * lum[i - w] - lum[i - w + 1];
      const e = Math.min(1, Math.sqrt(gx * gx + gy * gy) * 1.6);
      out.data[i * 4] = cr;
      out.data[i * 4 + 1] = cg;
      out.data[i * 4 + 2] = cb;
      out.data[i * 4 + 3] = e > 0.12 ? e * 255 : 0;
    }
  }
  g.clearRect(0, 0, w, h);
  g.putImageData(out, 0, 0);
  derived.set(key, c);
  return c;
};

