/** Image (or placeholder) for a member and kind. Expressions fall back to 'main'. */
/** The picture actually used for a kind: missing full-body expressions fall back to the plain full body,
 *  a missing chu picture to kiss, other missing expressions to main. */
export const resolveKind = (m: Member, k: Kind): Kind => {
  if (images.has(`${m}_${k}`)) return k;
  if (k.startsWith('full')) return 'full';
  if (k === 'chu' && images.has(`${m}_kiss`)) return 'kiss';
  if (k !== 'main' && images.has(`${m}_main`)) return 'main';
  return k;
};

export const img = (m: Member, k: Kind): Src => {
  const r = resolveKind(m, k);
  return images.get(`${m}_${r}`) ?? placeholder(m, r);
};

export const faceOf = (m: Member, k0: Kind): [number, number, number] => {
  const k = resolveKind(m, k0);
  return faces.get(`${m}_${k}`) ?? (images.has(`${m}_${k}`) ? DEFAULT_FACE[k] : k === 'full' ? [0.5, 0.11, 0.14] : [0.5, 0.22, 0.32]);
};

