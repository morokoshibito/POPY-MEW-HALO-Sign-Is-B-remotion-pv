import {continueRender, delayRender, getStaticFiles, staticFile} from 'remotion';
import {COLORS, Member, NAMES} from '../config';

// Character images live in public/chars/<member>_<kind>.png (see the prompt tab of the plan).
// Missing files are replaced by generated placeholders, so the project always renders.

/** Half-body pictures (main / laugh / wink / kiss / chu) and the full-body picture with its expression
 *  variants (full_*: the original full body with only the face replaced, so they swap without a jump). */
export type Kind = 'main' | 'full' | 'laugh' | 'wink' | 'kiss' | 'chu' | FullFace;
export type FullFace = 'full_laugh' | 'full_wink' | 'full_kiss' | 'full_soft' | 'full_smug';
export const FULL_FACES: FullFace[] = ['full_laugh', 'full_wink', 'full_kiss', 'full_soft', 'full_smug'];
export type Src = HTMLImageElement | HTMLCanvasElement;

/** Where the face sits in each image, as fractions of the image size (cx, cy, face height).
 *  Real images: override in public/chars/crops.json, e.g. {"popy_main": [0.52, 0.17, 0.16]}. */
const DEFAULT_FACE: Record<Kind, [number, number, number]> = {
  main: [0.5, 0.2, 0.2],
  laugh: [0.5, 0.2, 0.2],
  wink: [0.5, 0.2, 0.2],
  kiss: [0.5, 0.2, 0.2],
  full: [0.5, 0.09, 0.1],
  chu: [0.5, 0.2, 0.2],
  full_laugh: [0.5, 0.09, 0.1],
  full_wink: [0.5, 0.09, 0.1],
  full_kiss: [0.5, 0.09, 0.1],
  full_soft: [0.5, 0.09, 0.1],
  full_smug: [0.5, 0.09, 0.1],
};

const images = new Map<string, Src>();
const faces = new Map<string, [number, number, number]>();
const cuts = new Map<string, string[]>();
/** Picture borders where the figure is cut (hands, hair): they must stay outside the frame. */
export const cutsOf = (m: Member, k: Kind): string[] => cuts.get(`${m}_${k}`) ?? [];
let loaded = false;
let loading: Promise<void> | null = null;

const KINDS: Kind[] = ['main', 'full', 'laugh', 'wink', 'kiss', 'chu', ...FULL_FACES];

const loadImage = (url: string) =>
  new Promise<HTMLImageElement>((res, rej) => {
    const im = new Image();
    im.onload = () => res(im);
    im.onerror = () => rej(new Error(`cannot load ${url}`));
    im.src = url;
  });

export const loadAssets = (): Promise<void> => {
  if (loaded) return Promise.resolve();
  if (loading) return loading;
  const handle = delayRender('assets');
  loading = (async () => {
    for (const [fam, file] of [
      ['MPR', 'fonts/MPLUSRounded1c-Black.ttf'],
      ['MPR7', 'fonts/MPLUSRounded1c-700.ttf'],
      ['YUSEI', 'fonts/YuseiMagic-Regular.ttf'],
    ]) {
      const font = new FontFace(fam, `url(${staticFile(file)})`);
      await font.load();
      (document.fonts as unknown as {add: (f: FontFace) => void}).add(font);
    }
    const files = new Set(getStaticFiles().map((f) => f.name));
    if (files.has('chars/crops.json')) {
      const crops = await (await fetch(staticFile('chars/crops.json'))).json();
      for (const k of Object.keys(crops)) faces.set(k, crops[k]);
    }
    if (files.has('chars/cuts.json')) {
      const c = await (await fetch(staticFile('chars/cuts.json'))).json();
      for (const k of Object.keys(c)) cuts.set(k, c[k]);
    }
    for (const m of ['popy', 'mew', 'halo'] as Member[]) {
      for (const k of KINDS) {
        const name = `chars/${m}_${k}.png`;
        if (files.has(name)) images.set(`${m}_${k}`, await loadImage(staticFile(name)));
      }
    }
    // light textures (three.js examples, MIT): public/fx/lensflare*.png
    for (const name of ['lensflare0', 'lensflare2', 'lensflare3']) {
      const f = `fx/${name}.png`;
      if (files.has(f)) fxs.set(name, await loadImage(staticFile(f)));
    }
    // optional props generated by the user: public/props/<name>.png
    for (const name of ['mic', 'mic_black']) {
      const f = `props/${name}.png`;
      if (files.has(f)) props.set(name, await loadImage(staticFile(f)));
    }
    // optional stage backgrounds (generated by the user): public/bg/stage_pink.* and stage_gold.*
    for (const name of ['stage_pink', 'stage_gold']) {
      for (const ext of ['png', 'jpg', 'jpeg', 'webp']) {
        const f = `bg/${name}.${ext}`;
        if (files.has(f)) {
          bgs.set(name, await loadImage(staticFile(f)));
          break;
        }
      }
    }
    loaded = true;
    continueRender(handle);
  })();
  return loading;
};

