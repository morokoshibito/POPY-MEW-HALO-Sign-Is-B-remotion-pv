const placeholderCache = new Map<string, HTMLCanvasElement>();

/** A neutral stand-in figure: simple shapes in the member colour with a label. */
const placeholder = (m: Member, k: Kind): HTMLCanvasElement => {
  const key = `${m}_${k}`;
  const hit = placeholderCache.get(key);
  if (hit) return hit;
  const c = document.createElement('canvas');
  const full = k === 'full';
  c.width = full ? 700 : 900;
  c.height = full ? 1600 : 1200;
  const g = c.getContext('2d')!;
  const col = COLORS[m];
  const fill = g.createLinearGradient(0, 0, 0, c.height);
  fill.addColorStop(0, col.light);
  fill.addColorStop(1, col.main);
  g.fillStyle = fill;
  g.strokeStyle = col.deep;
  g.lineWidth = 10;
  g.lineJoin = 'round';
  const cx = c.width / 2;
  const blob = (path: () => void) => {
    g.beginPath();
    path();
    g.fill();
    g.stroke();
  };
  if (full) {
    const headR = 105;
    const headY = 165;
    blob(() => g.ellipse(cx, headY + 20, headR * 1.35, headR * 1.25, 0, 0, Math.PI * 2)); // hair
    blob(() => g.roundRect(cx - 120, 300, 240, 330, 60)); // torso
    blob(() => {
      g.moveTo(cx - 120, 560);
      g.lineTo(cx + 120, 560);
      g.lineTo(cx + 230, 860);
      g.lineTo(cx - 230, 860);
      g.closePath();
    }); // skirt
    blob(() => g.roundRect(cx - 95, 850, 70, 640, 34)); // legs
    blob(() => g.roundRect(cx + 25, 850, 70, 640, 34));
    blob(() => g.roundRect(cx - 110, 1480, 105, 70, 30)); // shoes
    blob(() => g.roundRect(cx + 10, 1480, 105, 70, 30));
    blob(() => {
      g.save();
      g.translate(cx + 110, 330);
      g.rotate(-2.4);
      g.roundRect(-30, 0, 60, 330, 30);
      g.restore();
    }); // raised arm
    blob(() => {
      g.save();
      g.translate(cx - 110, 330);
      g.rotate(0.7);
      g.roundRect(-30, 0, 60, 300, 30);
      g.restore();
    });
    blob(() => g.arc(cx, headY, headR, 0, Math.PI * 2)); // face
  } else {
    const headR = 190;
    const headY = 260;
    blob(() => g.ellipse(cx, headY + 30, headR * 1.35, headR * 1.3, 0, 0, Math.PI * 2));
    blob(() => g.roundRect(cx - 230, 470, 460, 760, 120)); // torso
    blob(() => {
      g.save();
      g.translate(cx + 200, 520);
      g.rotate(-1.0);
      g.roundRect(-45, 0, 90, 420, 45);
      g.restore();
    }); // arm toward camera
    blob(() => g.arc(cx, headY, headR, 0, Math.PI * 2));
  }
  // face marks: different per expression so the cut is visible in the animatic
  const fy = full ? 165 : 260;
  const fr = full ? 105 : 190;
  g.strokeStyle = col.deep;
  g.lineWidth = full ? 9 : 14;
  g.lineCap = 'round';
  const eye = (x: number, kind: 'open' | 'arc' | 'shut') => {
    g.beginPath();
    if (kind === 'open') g.arc(x, fy - fr * 0.05, fr * 0.09, 0, Math.PI * 2);
    else if (kind === 'arc') g.arc(x, fy, fr * 0.14, Math.PI * 1.1, Math.PI * 1.9);
    else {
      g.moveTo(x - fr * 0.14, fy - fr * 0.03);
      g.lineTo(x + fr * 0.14, fy - fr * 0.03);
    }
    g.stroke();
  };
  const ex = fr * 0.38;
  if (k === 'laugh') {
    eye(cx - ex, 'arc');
    eye(cx + ex, 'arc');
  } else if (k === 'wink' || k === 'kiss') {
    eye(cx - ex, 'open');
    eye(cx + ex, 'shut');
  } else {
    eye(cx - ex, 'open');
    eye(cx + ex, 'open');
  }
  g.beginPath();
  if (k === 'kiss') g.arc(cx, fy + fr * 0.45, fr * 0.08, 0, Math.PI * 2);
  else if (k === 'laugh') g.arc(cx, fy + fr * 0.3, fr * 0.22, 0.1, Math.PI - 0.1);
  else g.arc(cx, fy + fr * 0.3, fr * 0.16, 0.3, Math.PI - 0.3);
  g.stroke();
  // label
  const label = `${NAMES[m]} ${({main: '主立绘', full: '全身', laugh: '大笑', wink: '眨眼', kiss: '飞吻'} as Record<string, string>)[k] ?? k}`;
  g.font = `900 ${full ? 46 : 64}px MPR, sans-serif`;
  g.textAlign = 'center';
  g.lineWidth = 12;
  g.strokeStyle = '#ffffff';
  const ly = full ? 470 : 820;
  g.strokeText(label, cx, ly);
  g.fillStyle = col.deep;
  g.fillText(label, cx, ly);
  placeholderCache.set(key, c);
  return c;
};

